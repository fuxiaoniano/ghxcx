CREATE TABLE `website_pages` (
  `id` VARCHAR(32) NOT NULL,
  `slug` VARCHAR(80) NOT NULL,
  `title` VARCHAR(160) NOT NULL,
  `menuTitle` VARCHAR(40) NOT NULL,
  `summary` VARCHAR(500) NULL,
  `coverUrl` VARCHAR(500) NULL,
  `contentHtml` LONGTEXT NOT NULL,
  `seoTitle` VARCHAR(160) NULL,
  `seoDescription` VARCHAR(300) NULL,
  `showInNav` BOOLEAN NOT NULL DEFAULT true,
  `sort` INTEGER NOT NULL DEFAULT 0,
  `status` ENUM('ACTIVE', 'DISABLED') NOT NULL DEFAULT 'ACTIVE',
  `publishedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `website_pages_slug_key`(`slug`),
  INDEX `website_pages_status_showInNav_sort_idx`(`status`, `showInNav`, `sort`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `wechat_articles` (
  `id` VARCHAR(32) NOT NULL,
  `wechatArticleId` VARCHAR(191) NOT NULL,
  `mediaId` VARCHAR(191) NULL,
  `articleIndex` INTEGER NOT NULL DEFAULT 0,
  `slug` VARCHAR(191) NOT NULL,
  `title` VARCHAR(255) NOT NULL,
  `author` VARCHAR(100) NULL,
  `digest` TEXT NULL,
  `coverUrl` VARCHAR(1000) NULL,
  `contentHtml` LONGTEXT NOT NULL,
  `sourceUrl` VARCHAR(1000) NULL,
  `originalUrl` VARCHAR(1000) NULL,
  `syncHash` VARCHAR(64) NOT NULL,
  `status` ENUM('ACTIVE', 'DISABLED') NOT NULL DEFAULT 'ACTIVE',
  `publishedAt` DATETIME(3) NULL,
  `wechatUpdatedAt` DATETIME(3) NULL,
  `lastSyncedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `wechat_articles_wechatArticleId_key`(`wechatArticleId`),
  UNIQUE INDEX `wechat_articles_slug_key`(`slug`),
  INDEX `wechat_articles_status_publishedAt_idx`(`status`, `publishedAt`),
  INDEX `wechat_articles_mediaId_idx`(`mediaId`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
